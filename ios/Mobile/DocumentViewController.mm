- (void)showWriterCommentInfoFromJSON:(NSString *)json
{
    if (!documentReady || isClosing || self.document == nil ||
        ![nativeDocumentType isEqualToString:@"text"] || json.length == 0) {
        return;
    }
    NSData *data = [json dataUsingEncoding:NSUTF8StringEncoding];
    id parsed = data != nil ? [NSJSONSerialization JSONObjectWithData:data options:0 error:nil] : nil;
    if (![parsed isKindOfClass:[NSDictionary class]]) return;
    NSDictionary *payload = (NSDictionary *)parsed;
    NSString *kind = [payload[@"kind"] isKindOfClass:[NSString class]] ? payload[@"kind"] : @"comment";
    if (![kind isEqualToString:@"comment"] && ![kind isEqualToString:@"revision"]) return;
    NSString *commentId = [payload[@"id"] isKindOfClass:[NSString class]] ? payload[@"id"] : @"";
    if (commentId.length == 0 || [commentId isEqualToString:@"new"]) return;

    NSArray *comments = [payload[@"comments"] isKindOfClass:[NSArray class]] ? payload[@"comments"] : @[payload];
    NSMutableArray *validComments = [NSMutableArray array];
    for (id entry in comments) {
        if (![entry isKindOfClass:[NSDictionary class]]) continue;
        NSDictionary *item = (NSDictionary *)entry;
        NSString *itemId = [item[@"id"] isKindOfClass:[NSString class]] ? item[@"id"] : @"";
        if (itemId.length == 0 || [itemId isEqualToString:@"new"]) continue;
        NSMutableDictionary *normalized = [item mutableCopy];
        normalized[@"kind"] = kind;
        [validComments addObject:normalized];
    }
    if (validComments.count == 0) return;
    NSMutableDictionary *safePayload = [payload mutableCopy];
    safePayload[@"kind"] = kind;
    safePayload[@"comments"] = validComments;

    writerCommentInfoDocumentId = self.document->appDocId;
    writerCommentInfoGeneration++;
    writerCommentInfoActiveId = commentId;
    writerCommentInfoActionInFlight = NO;
    NSURL *support = [[[NSFileManager defaultManager] URLsForDirectory:NSApplicationSupportDirectory
                                                              inDomains:NSUserDomainMask] lastObject];
    NSURL *avatarURL = [support URLByAppendingPathComponent:@"ai_profile_avatar.jpg"];
    UIImage *avatar = [UIImage imageWithContentsOfFile:avatarURL.path] ?: [AppIcons iconNamed:@"avatar"];
    NSString *ownAuthorName = [self currentIOSUserNameForWeb] ?: @"";
    __weak DocumentViewController *weakSelf = self;
    [CommentInfoOverlay showInHostViewController:self
                                         comment:safePayload
                                  ownAuthorName:ownAuthorName
                                         avatar:avatar
                                        canEdit:nativeEditMode
                                         onClose:^{
        [weakSelf hideWriterCommentInfoClearingWebState];
    }
                                          onEdit:^(NSString *itemId, NSString *text) {
        [weakSelf runWriterCommentInfoAction:@"__coolEditWriterCommentInfo" commentId:itemId text:text];
    }
                                        onDelete:^(NSString *itemId, NSString *text) {
        [weakSelf runWriterCommentInfoAction:@"__coolDeleteWriterCommentInfo" commentId:itemId text:text];
    }];
    // First-tap priority: release only the document WebView's text input so
    // the info card stays read-only and the late caret hook cannot reopen IME.
    [self.webView endEditing:YES];
}

