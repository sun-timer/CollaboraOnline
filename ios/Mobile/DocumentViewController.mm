- (NSString *)documentCanvasRecoverJavaScript
{
    // The first iOS layout can finish before LOK has a usable canvas.  A single
    // invalidateSize() is not enough in that case: the first tile request can
    // be made with stale client zoom/viewport values and leave the preview
    // white until the document is reopened.  Keep this in parity with the
    // Android visible-tile recovery sequence and retry while the socket/core
    // is still connecting.
    return @"(function(){try{"
            "var maxRetries=75;"
            "function mapReady(){"
              "var map=window.app&&app.map;"
              "if(!map||typeof map.invalidateSize!=='function'||!map._loaded){return null;}"
              "var size=typeof map.getSize==='function'?map.getSize():null;"
              "var canvas=document.getElementById('canvas-container');"
              "var rect=canvas&&typeof canvas.getBoundingClientRect==='function'?canvas.getBoundingClientRect():null;"
              "if((!size||size.x<1||size.y<1)&&(!rect||rect.width<1||rect.height<1)){return null;}"
              "if(window.app&&app.socket&&typeof app.socket.isTemporarilyReconnecting==='function'&&app.socket.isTemporarilyReconnecting()){return null;}"
              "return map;"
            "}"
            "function recover(tag,hard,retry){"
                "try{"
                "var map=mapReady();"
                "if(!map){if(retry<maxRetries){setTimeout(function(){recover(tag,hard,retry+1);},120);}return;}"
                "if(typeof window.dispatchEvent==='function'&&typeof Event==='function'){window.dispatchEvent(new Event('resize'));}"
                "map._sizeChanged=true;"
                "map.invalidateSize(false);"
                "var layer=map._docLayer;"
                "if(layer&&typeof layer._resetClientVisArea==='function'){layer._resetClientVisArea();}"
                "if(layer&&typeof layer._sendClientZoom==='function'){layer._sendClientZoom(true);}"
                "if(layer&&typeof layer._requestNewTiles==='function'){layer._requestNewTiles();}"
                "var tm=window.TileManager||(typeof TileManager!=='undefined'?TileManager:null);"
                "if(tm&&typeof tm.refreshTilesInBackground==='function'){tm.refreshTilesInBackground();}"
                "if(tm&&typeof tm.update==='function'){tm.update();}"
                "if(window.app&&app.sectionContainer&&typeof app.sectionContainer.requestReDraw==='function'){app.sectionContainer.requestReDraw();}"
                "if(hard&&tm&&typeof tm.redraw==='function'){tm.redraw();}"
                "if(hard){var canvas=document.getElementById('document-canvas');"
                "var box=document.getElementById('canvas-container');"
                "var boxRect=box&&typeof box.getBoundingClientRect==='function'?box.getBoundingClientRect():null;"
                "if(canvas&&((canvas.width>0&&canvas.height>0)||(boxRect&&boxRect.width>1&&boxRect.height>1))){canvas.style.visibility='visible';}}"
                "if(window.app&&app.console&&typeof app.console.debug==='function'){app.console.debug('ios canvas recover tag='+tag+' hard='+hard);}"
              "}catch(e){"
                "if(retry<maxRetries){setTimeout(function(){recover(tag,hard,retry+1);},120);}"
                "else if(window.console&&console.warn){console.warn('ios_canvas_recover_failed',e);}"
              "}"
            "}"
            "function canvasShown(){"
              "var canvas=document.getElementById('document-canvas');"
              "if(!canvas||canvas.style.visibility==='hidden'){return false;}"
              "var box=document.getElementById('canvas-container');"
              "var boxRect=box&&typeof box.getBoundingClientRect==='function'?box.getBoundingClientRect():null;"
              "return (canvas.width>0&&canvas.height>0)||(boxRect&&boxRect.width>1&&boxRect.height>1);"
            "}"
            "if(canvasShown()){return 'visible';}"
            "setTimeout(function(){recover('soon',false,0);},120);"
            "setTimeout(function(){recover('mid',false,0);},420);"
            "setTimeout(function(){recover('late',false,0);},900);"
            "setTimeout(function(){recover('final',true,0);},1700);"
            "return 'pending';"
            "}catch(e){console.error('canvas_recover '+String(e&&e.message||e));return 'err';}})();";
}

- (BOOL)isDocumentOpeningStateVisible
{
    return documentOpeningStateWanted && documentOpeningOverlay != nil
        && !documentOpeningOverlay.hidden;
}

- (void)attachDocumentOpeningOverlay
{
    if (!documentOpeningStateWanted || self.webView == nil) {
        return;
    }
    if (documentOpeningOverlay == nil) {
        UIView *overlay = [[UIView alloc] init];
        overlay.translatesAutoresizingMaskIntoConstraints = NO;
        overlay.backgroundColor = UIColor.clearColor;
        overlay.opaque = NO;

        UILabel *label = [[UILabel alloc] init];
        label.translatesAutoresizingMaskIntoConstraints = NO;
        label.text = @"正在打开";
        label.textAlignment = NSTextAlignmentCenter;
        label.textColor = [UIColor colorWithRed:32.0 / 255.0
                                           green:33.0 / 255.0
                                            blue:36.0 / 255.0
                                           alpha:1.0];
        label.font = [UIFont systemFontOfSize:16.0];

        UIActivityIndicatorView *indicator = [[UIActivityIndicatorView alloc]
            initWithActivityIndicatorStyle:UIActivityIndicatorViewStyleMedium];
        indicator.translatesAutoresizingMaskIntoConstraints = NO;
        indicator.color = label.textColor;
        indicator.hidesWhenStopped = YES;

        UIStackView *stack = [[UIStackView alloc] initWithArrangedSubviews:@[ label, indicator ]];
        stack.translatesAutoresizingMaskIntoConstraints = NO;
        stack.axis = UILayoutConstraintAxisVertical;
        stack.alignment = UIStackViewAlignmentCenter;
        stack.spacing = 12.0;
        [overlay addSubview:stack];
        [NSLayoutConstraint activateConstraints:@[
            [stack.centerXAnchor constraintEqualToAnchor:overlay.centerXAnchor],
            [stack.centerYAnchor constraintEqualToAnchor:overlay.centerYAnchor],
        ]];

        documentOpeningOverlay = overlay;
        documentOpeningIndicator = indicator;
    }
    if (documentOpeningOverlay.superview != self.view) {
        [documentOpeningOverlay removeFromSuperview];
        [self.view insertSubview:documentOpeningOverlay aboveSubview:self.webView];
        [NSLayoutConstraint activateConstraints:@[
            [documentOpeningOverlay.topAnchor constraintEqualToAnchor:self.webView.topAnchor],
            [documentOpeningOverlay.leadingAnchor constraintEqualToAnchor:self.webView.leadingAnchor],
            [documentOpeningOverlay.trailingAnchor constraintEqualToAnchor:self.webView.trailingAnchor],
            [documentOpeningOverlay.bottomAnchor constraintEqualToAnchor:self.webView.bottomAnchor],
        ]];
    }
    documentOpeningOverlay.hidden = NO;
    [documentOpeningIndicator startAnimating];
}

- (void)showDocumentOpeningState
{
    documentOpeningEpoch += 1;
    documentOpeningStateWanted = YES;
    documentOpeningCanvasMayHide = NO;
    documentCanvasRecoverAttempts = 0;
    documentCanvasRecoverSucceeded = NO;
    documentCanvasRecoverInFlight = NO;
    [self attachDocumentOpeningOverlay];
}

- (void)hideDocumentOpeningState
{
    documentOpeningStateWanted = NO;
    documentOpeningCanvasMayHide = NO;
    [documentOpeningIndicator stopAnimating];
    documentOpeningOverlay.hidden = YES;
}

- (void)retryDocumentCanvasRecover
{
    const int openingEpoch = documentOpeningEpoch;
    documentCanvasRecoverInFlight = YES;
    __weak DocumentViewController *weakSelf = self;
    dispatch_after(dispatch_time(DISPATCH_TIME_NOW, (int64_t)(0.2 * NSEC_PER_SEC)),
                   dispatch_get_main_queue(), ^{
        DocumentViewController *retrySelf = weakSelf;
        if (retrySelf == nil || retrySelf->isClosing
            || retrySelf->documentOpeningEpoch != openingEpoch) {
            return;
        }
        retrySelf->documentCanvasRecoverInFlight = NO;
        [retrySelf scheduleDocumentCanvasRecover];
    });
}

- (void)evaluateDocumentCanvasRecoverOnce
{
    if (isClosing || self.webView == nil) {
        return;
    }
    [self sendToolbarJavaScript:[self documentCanvasRecoverJavaScript]];
}

- (void)scheduleDocumentCanvasRecover
{
    if (isClosing || self.webView == nil || documentCanvasRecoverSucceeded
        || documentCanvasRecoverInFlight) {
        return;
    }
    // The previous document's canvas is still in the web view until the new
    // load finishes. Keep the indicator up without treating that as success.
    if ([self isDocumentOpeningStateVisible] && !documentOpeningCanvasMayHide) {
        [self retryDocumentCanvasRecover];
        return;
    }
    CGSize boundsSize = self.webView.bounds.size;
    const BOOL boundsReady = boundsSize.width >= 1.0 && boundsSize.height >= 1.0;
    if (!boundsReady && ![self isDocumentOpeningStateVisible]) {
        return;
    }
    if (documentCanvasRecoverAttempts >= 24) {
        LOG_ERR("document canvas recover gave up after 24 attempts");
        [self hideDocumentOpeningState];
        return;
    }
    if (!boundsReady) {
        documentCanvasRecoverAttempts += 1;
        [self retryDocumentCanvasRecover];
        return;
    }
    documentCanvasRecoverAttempts += 1;
    documentCanvasRecoverInFlight = YES;
    const int openingEpoch = documentOpeningEpoch;
    __weak DocumentViewController *weakSelf = self;
    [self.webView evaluateJavaScript:[self documentCanvasRecoverJavaScript]
                   completionHandler:^(id result, NSError *error) {
        DocumentViewController *strongSelf = weakSelf;
        if (strongSelf == nil || strongSelf->isClosing
            || strongSelf->documentOpeningEpoch != openingEpoch) {
            return;
        }
        strongSelf->documentCanvasRecoverInFlight = NO;
        if (error) {
            LOG_ERR("document canvas recover JS failed: "
                    << [[error localizedDescription] UTF8String]);
        }
        NSString *status = [result isKindOfClass:[NSString class]] ? (NSString *)result : @"err";
        if ([status isEqualToString:@"visible"]) {
            if ([strongSelf isDocumentOpeningStateVisible]
                && !strongSelf->documentOpeningCanvasMayHide) {
                [strongSelf retryDocumentCanvasRecover];
                return;
            }
