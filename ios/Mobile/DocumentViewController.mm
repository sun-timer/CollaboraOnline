    [self attachKeyboardAccessoryToWebContentView];
    if (self.webView == nil) {
        return;
    }
    CGSize currentSize = self.webView.bounds.size;
    const BOOL firstValidLayout =
        lastWebViewLayoutSize.width < 1.0 || lastWebViewLayoutSize.height < 1.0;
    if (currentSize.width < 1.0 || currentSize.height < 1.0) {
        return;
    }
    const BOOL sizeChanged =
        fabs(currentSize.width - lastWebViewLayoutSize.width) > 1.0
        || fabs(currentSize.height - lastWebViewLayoutSize.height) > 1.0;
