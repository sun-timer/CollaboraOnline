- (void)runWriterCommentInfoAction:(NSString *)functionName commentId:(NSString *)commentId text:(NSString *)text
{
    if (isClosing || !documentReady || self.document == nil || self.webView == nil ||
        writerCommentInfoDocumentId != self.document->appDocId ||
        ![nativeDocumentType isEqualToString:@"text"] || !nativeEditMode || commentId.length == 0 ||
        (![functionName isEqualToString:@"__coolEditWriterCommentInfo"] &&
         ![functionName isEqualToString:@"__coolDeleteWriterCommentInfo"])) {
        [self hideWriterCommentInfoClearingWebState];
        return;
    }
    if (writerCommentInfoActionInFlight) return;
    NSArray *arguments = [functionName isEqualToString:@"__coolEditWriterCommentInfo"]
        ? @[commentId, text ?: @""] : @[commentId];
    NSData *argumentData = [NSJSONSerialization dataWithJSONObject:arguments options:0 error:nil];
    NSString *argumentJSON = argumentData != nil
        ? [[NSString alloc] initWithData:argumentData encoding:NSUTF8StringEncoding] : nil;
    if (argumentJSON == nil) {
        return;
    }
    NSString *script = [NSString stringWithFormat:
        @"(function(a){if(typeof window.%@==='function'){return window.%@.apply(window,a);}return false;})(%@);",
        functionName, functionName, argumentJSON];
    WKWebView *actionWebView = self.webView;
    int actionDocumentId = self.document->appDocId;
    NSUInteger actionGeneration = writerCommentInfoGeneration;
    NSString *activeCommentId = [writerCommentInfoActiveId copy];
    writerCommentInfoActionInFlight = YES;
    __weak DocumentViewController *weakSelf = self;
    [actionWebView evaluateJavaScript:script completionHandler:^(id result, NSError *error) {
        DocumentViewController *owner = weakSelf;
        if (owner == nil || owner->isClosing || !owner->documentReady ||
            owner.webView != actionWebView || owner.document == nil ||
            owner.document->appDocId != actionDocumentId ||
            owner->writerCommentInfoGeneration != actionGeneration ||
            ![owner->writerCommentInfoActiveId isEqualToString:activeCommentId]) {
            return;
        }
        owner->writerCommentInfoActionInFlight = NO;
        if (error != nil || ![result isKindOfClass:[NSNumber class]] || ![result boolValue]) {
            LOG_ERR("Writer comment info action was rejected or failed: "
                    << (error != nil ? [[error localizedDescription] UTF8String] : "callback returned false"));
            return;
        }
        // The successful web callback already cleared its active id. Hide only
        // this generation locally; an extra JS clear could erase a newer card.
        owner->writerCommentInfoGeneration++;
        owner->writerCommentInfoDocumentId = 0;
        owner->writerCommentInfoActiveId = nil;
        [CommentInfoOverlay hideFromHostViewController:owner];
    }];
}

- (void)presentWriterCommentListFromJson:(NSString *)json
{
    NSData *data = [json dataUsingEncoding:NSUTF8StringEncoding];
    if (data == nil) {
        [self presentWriterCommentList:@[]];
        return;
    }
    id parsed = [NSJSONSerialization JSONObjectWithData:data options:0 error:nil];
    if (![parsed isKindOfClass:[NSDictionary class]]) {
        [self presentWriterCommentList:@[]];
        return;
    }
    NSArray *rawComments = ((NSDictionary *)parsed)[@"comments"];
    if (![rawComments isKindOfClass:[NSArray class]]) {
        [self presentWriterCommentList:@[]];
        return;
    }
    NSMutableArray<WriterCommentListItem *> *items = [NSMutableArray array];
    for (id entry in rawComments) {
        if (![entry isKindOfClass:[NSDictionary class]]) {
            continue;
        }
        NSDictionary *dict = (NSDictionary *)entry;
        WriterCommentListItem *item = [[WriterCommentListItem alloc] init];
        item.commentId = [dict[@"id"] isKindOfClass:[NSString class]] ? dict[@"id"] : @"";
        item.author = [dict[@"author"] isKindOfClass:[NSString class]] ? dict[@"author"] : @"";
        item.text = [dict[@"text"] isKindOfClass:[NSString class]] ? dict[@"text"] : @"";
        item.dateTime = [dict[@"dateTime"] isKindOfClass:[NSString class]] ? dict[@"dateTime"] : @"";
        if (item.commentId.length > 0) {
            [items addObject:item];
        }
    }
    [self presentWriterCommentList:items];
}

