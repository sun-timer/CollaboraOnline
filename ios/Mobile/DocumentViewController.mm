- (void)openWriterCamera
{
    cameraPickerDocumentId = self.document ? self.document->appDocId : -1;
    const int expectedDocumentId = cameraPickerDocumentId;
    if (![UIImagePickerController isSourceTypeAvailable:UIImagePickerControllerSourceTypeCamera]) {
        UIAlertController *notice = [UIAlertController alertControllerWithTitle:@"无法使用相机"
            message:@"此设备当前没有可用的相机。您可以从相册选择图片。"
            preferredStyle:UIAlertControllerStyleAlert];
        [notice addAction:[UIAlertAction actionWithTitle:@"好" style:UIAlertActionStyleDefault handler:nil]];
        [self presentViewController:notice animated:YES completion:nil];
        return;
    }
    AVAuthorizationStatus status = [AVCaptureDevice authorizationStatusForMediaType:AVMediaTypeVideo];
    if (status == AVAuthorizationStatusDenied || status == AVAuthorizationStatusRestricted) {
        [self showWriterCameraPermissionNotice];
        return;
    }
    void (^presentCamera)(void) = ^{
        if (!self.document || self.document->appDocId != expectedDocumentId || self->isClosing) return;
        UIImagePickerController *picker = [[UIImagePickerController alloc] init];
        picker.sourceType = UIImagePickerControllerSourceTypeCamera;
        picker.mediaTypes = @[ UTTypeImage.identifier ];
        picker.delegate = self;
        picker.allowsEditing = NO;
        [self presentViewController:picker animated:YES completion:nil];
    };
    if (status == AVAuthorizationStatusNotDetermined) {
        [AVCaptureDevice requestAccessForMediaType:AVMediaTypeVideo completionHandler:^(BOOL granted) {
            if (granted) dispatch_async(dispatch_get_main_queue(), presentCamera);
            else dispatch_async(dispatch_get_main_queue(), ^{
                if (self.document && self.document->appDocId == expectedDocumentId && !self->isClosing)
                    [self showWriterCameraPermissionNotice];
            });
        }];
    } else {
        presentCamera();
    }
}

- (void)showWriterCameraPermissionNotice
