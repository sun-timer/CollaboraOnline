- (void)launchAIRequestWithTaskType:(NSString *)taskType title:(NSString *)title
{
    [self invalidateAutoGenerateChatPrompt];
    aiTaskTitle = title;
    lastTaskType = taskType;
    aiRequestId = [[NSUUID UUID] UUIDString];
    aiFullText = @"";

    [self dismissAIPanel];
    __weak DocumentViewController *weakSelf = self;
    aiResultModal = [[WriterAAIResultModal alloc] initWithTitle:title
        onClose:^{
            DocumentViewController *strongSelf = weakSelf;
            [strongSelf cancelAIGeneration];
            [strongSelf dismissAIResultModal];
        }
        onStop:^{
            DocumentViewController *strongSelf = weakSelf;
            [strongSelf cancelAIGeneration];
            if (strongSelf->aiResultModal) {
                [strongSelf->aiResultModal setReadyWithFullText:strongSelf->aiFullText ?: @""];
            }
        }
        onRetry:^{
            DocumentViewController *strongSelf = weakSelf;
            [strongSelf retryAIGeneration];
        }
        onInsert:^{
            DocumentViewController *strongSelf = weakSelf;
            [strongSelf insertAIText];
        }
        onCopy:^{
            DocumentViewController *strongSelf = weakSelf;
            [strongSelf copyAIText];
        }];
    [aiResultModal showIn:self.view];

    NSMutableDictionary *payload = [@{
        @"taskType": taskType,
        @"selection": lastSelection ?: @"",
        @"modelMode": @"cloud",
    } mutableCopy];
    if ([taskType isEqualToString:@"translate"] && translateTargetLang.length > 0) {
        payload[@"context"] = @{@"targetLang": translateTargetLang};
    }
    __weak DocumentViewController *aiWeakSelf = self;
    [self->aiService startRequest:payload
                       requestId:aiRequestId
              documentSessionId:@"ai-panel-local"
                           emit:^(NSString *type, NSString *reqId, NSString *dsid, NSDictionary *eventPayload) {
        DocumentViewController *strongSelf = aiWeakSelf;
        if (strongSelf) {
            [strongSelf aiEventReceived:type requestId:reqId payload:eventPayload];
        }
    }];
}

- (void)aiEventReceived:(NSString *)type requestId:(NSString *)reqId payload:(NSDictionary *)payload
{
    if (!aiResultModal || ![reqId isEqualToString:aiRequestId]) {
        return;
    }
    if (autoGenerateChatPromptActive && autoGenerateInsertPending) {
        return;
    }
    if ([type isEqualToString:@"ai.stream"]) {
        NSString *delta = payload[@"delta"];
        if ([delta isKindOfClass:[NSString class]]) {
            aiFullText = [aiFullText stringByAppendingString:delta];
            [aiResultModal setStreamingText:aiFullText];
        }
    } else if ([type isEqualToString:@"ai.done"]) {
        id fullText = payload[@"fullText"];
        aiFullText = [fullText isKindOfClass:[NSString class]] ? fullText : @"";
        if (autoGenerateChatPromptActive) {
            NSString *trimmedText = [aiFullText stringByTrimmingCharactersInSet:[NSCharacterSet whitespaceAndNewlineCharacterSet]];
            if (trimmedText.length == 0) {
                [aiResultModal setErrorWithMessage:@"AI 未返回可插入的内容，请重试"];
            } else {
                [aiResultModal setInsertingText:aiFullText];
                [self insertAutoGeneratedChatPromptForRequestId:reqId generation:autoGenerateGeneration];
            }
        } else {
            [aiResultModal setReadyWithFullText:aiFullText];
        }
    } else if ([type isEqualToString:@"ai.error"]) {
        NSString *message = [payload[@"message"] isKindOfClass:[NSString class]]
                                ? payload[@"message"]
                                : @"AI 请求失败";
        [aiResultModal setErrorWithMessage:message];
    }
}

- (void)insertAutoGeneratedChatPromptForRequestId:(NSString *)requestId generation:(NSUInteger)generation
{
    if (!autoGenerateChatPromptActive || autoGenerateInsertPending || autoGenerateInserted
        || aiFullText.length == 0 || isClosing || generation != autoGenerateGeneration
        || ![requestId isEqualToString:autoGenerateRequestId] || ![requestId isEqualToString:aiRequestId]
        || !self.document || self.document->appDocId != autoGenerateDocumentId) {
        return;
    }
    autoGenerateInsertPending = YES;
    WKWebView *expectedWebView = self.webView;
    int expectedDocumentId = autoGenerateDocumentId;
    NSMutableString *escaped = [aiFullText mutableCopy];
    [escaped replaceOccurrencesOfString:@"&" withString:@"&amp;" options:0 range:NSMakeRange(0, escaped.length)];
    [escaped replaceOccurrencesOfString:@"<" withString:@"&lt;" options:0 range:NSMakeRange(0, escaped.length)];
    [escaped replaceOccurrencesOfString:@">" withString:@"&gt;" options:0 range:NSMakeRange(0, escaped.length)];
    [escaped replaceOccurrencesOfString:@"\n" withString:@"<br>" options:0 range:NSMakeRange(0, escaped.length)];
    NSString *html = [NSString stringWithFormat:@"<p>%@</p>", escaped];
    __weak DocumentViewController *weakSelf = self;
    [expectedWebView evaluateJavaScript:@"(function(){var id=window.app&&app.map&&app.map._docLayer?app.map._docLayer._viewId:null;return Number.isInteger(id)?id:-1;})();"
                    completionHandler:^(id result, NSError *error) {
        DocumentViewController *strongSelf = weakSelf;
        if (!strongSelf || !strongSelf->autoGenerateChatPromptActive || strongSelf->isClosing
            || generation != strongSelf->autoGenerateGeneration
            || ![requestId isEqualToString:strongSelf->autoGenerateRequestId]
            || ![requestId isEqualToString:strongSelf->aiRequestId]
            || strongSelf.webView != expectedWebView || !strongSelf.document
            || strongSelf.document->appDocId != expectedDocumentId) return;
        NSInteger viewId = [result respondsToSelector:@selector(integerValue)] ? [result integerValue] : -1;
        if (error || viewId < 0 || !strongSelf->nativeBridgeHandler.documentTextInserter) {
            strongSelf->autoGenerateInsertPending = NO;
            [strongSelf->aiResultModal setErrorWithMessage:@"无法定位文档插入位置，请重试"];
            return;
        }
        strongSelf->nativeBridgeHandler.documentTextInserter(html, viewId, @"insertAtEnd", ^(BOOL inserted, NSString *message) {
            DocumentViewController *completionSelf = weakSelf;
            if (!completionSelf) return;
            if (completionSelf->isClosing || !completionSelf->autoGenerateChatPromptActive
                || generation != completionSelf->autoGenerateGeneration
                || ![requestId isEqualToString:completionSelf->autoGenerateRequestId]
                || ![requestId isEqualToString:completionSelf->aiRequestId]
                || completionSelf.webView != expectedWebView || !completionSelf.document
                || completionSelf.document->appDocId != expectedDocumentId) return;
            completionSelf->autoGenerateInsertPending = NO;
            if (inserted) {
                completionSelf->autoGenerateInserted = YES;
                completionSelf->autoGenerateChatPromptActive = NO;
                if (completionSelf.document->fakeClientFd >= 0) {
                    const char *saveMessage = "save dontTerminateEdit=1 dontSaveIfUnmodified=1";
                    fakeSocketWriteQueue(completionSelf.document->fakeClientFd, saveMessage, strlen(saveMessage));
                }
                [completionSelf dismissAIResultModal];
            } else {
                [completionSelf->aiResultModal setErrorWithMessage:message ?: @"插入失败，请重试"];
            }
        });
    }];
}

