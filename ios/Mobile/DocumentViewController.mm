    UIAlertController *notice = [UIAlertController alertControllerWithTitle:@"需要相机权限"
        message:@"请在系统设置中允许 Collabora 使用相机，或从相册选择图片。"
        preferredStyle:UIAlertControllerStyleAlert];
    [notice addAction:[UIAlertAction actionWithTitle:@"取消" style:UIAlertActionStyleCancel handler:nil]];
