        return;
    }
    lastWebViewLayoutSize = currentSize;
    if (!firstValidLayout) {
        documentCanvasRecoverAttempts = 0;
        documentCanvasRecoverSucceeded = NO;
    }
    [self scheduleDocumentCanvasRecover];
}

