}

- (void)imagePickerController:(UIImagePickerController *)picker didFinishPickingMediaWithInfo:(NSDictionary<UIImagePickerControllerInfoKey,id> *)info
{
    UIImage *image = info[UIImagePickerControllerOriginalImage];
    [picker dismissViewControllerAnimated:YES completion:nil];
    if (!image || !self.document || self.document->appDocId != cameraPickerDocumentId || isClosing) return;
    // Drawing through UIKit applies the camera's EXIF orientation before the
    // bytes cross into the document, so the inserted image has stable bounds.
    NSData *data = nil;
    if (image.imageOrientation == UIImageOrientationUp) {
        data = UIImagePNGRepresentation(image);
    } else {
        UIGraphicsImageRendererFormat *format = [[UIGraphicsImageRendererFormat alloc] init];
        format.scale = 1.0;
        UIGraphicsImageRenderer *renderer = [[UIGraphicsImageRenderer alloc] initWithSize:image.size format:format];
        UIImage *upright = [renderer imageWithActions:^(UIGraphicsImageRendererContext * _Nonnull context) {
            [image drawInRect:(CGRect){CGPointZero, image.size}];
        }];
        data = UIImagePNGRepresentation(upright);
    }
    if (!data) return;
    NSString *base64 = [data base64EncodedStringWithOptions:0];
    NSString *name = [NSString stringWithFormat:@"camera_%ld.png", (long)[[NSDate date] timeIntervalSince1970]];
    NSString *js = [NSString stringWithFormat:@"if(window.postMobileMessage){window.postMobileMessage('insertfile name=%@ type=graphic data=%@');}", name, base64];
    [self sendToolbarJavaScript:js];
}

